def career():
    out = []
    for r in rows[:100]:
        ans = norm(r["התשובה הנכונה"])
        path = norm(r["השאלה"].split("? ", 1)[1])
        pool = POS.get(ans)
        if pool is None:
            raise SystemExit(f"no position for {ans}")
        rnd = random.Random(ans)
        wrong = rnd.sample([n for n in pool if n != ans], 5)
        level = "m" if ans in MEDIUM else "e" if ans in EXPERT else "h"
        out.append({"l": level, "t": "p", "q": f"של מי מסלול הקריירה הזה? {path}", "a": ans, "w": wrong,
                    "x": "תחנות נבחרות לפי הסדר, בלי כל ההשאלות."})
    return out

